DYN=[(re.compile(r'(\d[\d,]*) מתוך (\d[\d,]*) נרשמו לעדכונים'),r'\1 من أصل \2 اشتركوا في التحديثات'),
     (re.compile(r'(\d[\d,]*) מתוך (\d[\d,]*) תומכים חודשיים'),r'\1 من أصل \2 داعمين شهريين')]
def tr(x,miss):
    core=x.strip()
    if core in AR: return x.replace(core,AR[core])
    for rx,rep in DYN:
        if rx.fullmatch(core): return x.replace(core,rx.sub(rep,core))
    miss.append(core); return x
def main():
    miss=[]
    src=open(R+'donate/index.html',encoding='utf-8').read()
    sys.path.insert(0,os.path.dirname(os.path.abspath(__file__)))
    import donate_text
    src=donate_text.bake(src,'ar')   # texts that live in content/donate.json come straight from there
    parts=re.split(r'(?s)(<style.*?</style>)',src)
    for i in range(0,len(parts),2):
        t=parts[i]
        t=re.sub(r'(?s)(<script.*?</script>)|>([^<>]+)<',lambda m:m.group(1) if m.group(1) else ('>'+tr(m.group(2),miss)+'<' if H.search(m.group(2)) else m.group(0)),t)
        t=re.sub(r'<title>([^<]*)</title>',lambda m:'<title>'+tr(m.group(1),miss)+'</title>',t)
        t=re.sub(r'\b([\w-]+)="([^"]*[֐-׿][^"]*)"',lambda m:f'{m.group(1)}="{tr(m.group(2),miss).replace(chr(34),"&quot;")}"',t)
        # JS string literals
        t=re.sub(r'"([^"<>\n;(){}=]*[\u0590-\u05ff][^"<>\n;(){}=]*)"',lambda m:'"'+tr(m.group(1),miss)+'"',t) if '<script>' in t else t
        parts[i]=t
    s=''.join(parts)
    s=s.replace('<html lang="he" dir="rtl">','<html lang="ar" dir="rtl">')
    s=s.replace("'Heebo', system-ui, sans-serif","'Noto Sans Arabic', 'Heebo', system-ui, sans-serif").replace("'Heebo', sans-serif","'Noto Kufi Arabic', sans-serif")
    s=re.sub(r'<link rel="stylesheet" href="https://fonts.googleapis.com/css2\?[^"]*">','<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Noto+Kufi+Arabic:wght@500;600;700;800&amp;family=Noto+Sans+Arabic:wght@400;500;600;700;800&amp;family=Heebo:wght@400;500;600;700;800&amp;display=swap">',s)
    # links
    for a,b in (('href="/plan/"','href="/ar/plan/"'),('href="/projects/"','href="/ar/projects/"'),('href="/#','href="/ar/#'),('href="/privacy/"','href="/ar/privacy/"'),('href="/accessibility/"','href="/ar/accessibility/"')):
        s=s.replace(a,b)
    s=re.sub(r'<a href="/" ',r'<a href="/ar/" ',s)           # logos
    s=s.replace('href="/ar/#','href="/ar/#')
    # language switcher: current = ar, he -> /donate/, en -> /en/donate/
    def trio(m):
        pad=re.search(r'padding: [^;]*',m.group(0)).group(0); label=m.group(1)
        tgt={'עב':'he','عر':'ar','En':'en'}[label]; cur=tgt=='ar'
        href={'he':'/donate/','ar':'/ar/donate/','en':'/en/donate/'}[tgt]
        st=f'{pad}; font-weight: 800; color: #3B1D12; text-decoration: none' if cur else f'{pad}; color: #6B4A3A; text-decoration: none'
        return f'<a href="{href}"'+(' aria-current="true"' if cur else f' lang="{tgt}"')+f' style="{st}">{label}</a>'
    s=re.sub(r'<a href="[^"]*"(?: aria-current="[^"]*")?(?: lang="[a-z]+")? style="[^"]*">(עב|عر|En)</a>',trio,s)
    s=s.replace('href="/donate/" aria-current="true"','href="/ar/donate/" aria-current="true"')
    s=re.sub(r'(<a href="[^"]*" )(style="[^"]*"[^>]*>)تبرّع</a>',lambda m:m.group(0),s)
    # donate buttons in header point to the in-page form
    s=s.replace('<link rel="alternate" hreflang="he"','<link rel="alternate" hreflang="ar" href="https://negevvillages.org/ar/donate/">\n<link rel="alternate" hreflang="he"',1) if 'hreflang="ar"' not in s else s
    s=re.sub(r'(<meta property="og:url" content=")[^"]*"',r'\1https://negevvillages.org/ar/donate/"',s)
    os.makedirs(R+'ar/donate',exist_ok=True)
    open(R+'ar/donate/index.html','w',encoding='utf-8').write(s)
    # keep he/en language links pointing at the Arabic donate page + hreflang
    for f in ('donate/index.html','en/donate/index.html'):
        p=R+f; t=open(p,encoding='utf-8').read(); o=t
        t=t.replace('href="/ar/" lang="ar"','href="/ar/donate/" lang="ar"')
        if 'hreflang="ar"' not in t:
            t=t.replace('<link rel="alternate" hreflang="en"','<link rel="alternate" hreflang="ar" href="https://negevvillages.org/ar/donate/">\n<link rel="alternate" hreflang="en"',1)
        if t!=o: open(p,'w',encoding='utf-8').write(t)
    left=[m for m in miss if H.search(m) and '\n' not in m and '(' not in m]
    print('MISSING translations:',len(left))
    for m in left: print(' -',m[:100])
